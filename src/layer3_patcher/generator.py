"""Layer 3: parser patch synthesis, driven by the pipeline's own schema.

Two defects shaped this rewrite.

First, the generator hardcoded the eight weather field names, so a patch
generated for the finance, e-commerce or IoT pipeline emitted zero-filled
weather fields and discarded the real payload -- total data loss, reported as
a successful heal. Schema, ranges and defaults are now supplied by the caller.

Second, `generate_patch` accepted a `feedback_context` argument and never read
it, so the orchestrator's three "retry with traceback feedback" attempts
produced byte-identical code and therefore identical failures. Attempts now
escalate through genuinely different strategies.

The emitted parser is also table-driven rather than an unrolled block per
field, which keeps it short and readable, and it is restricted to the syntax
subset accepted by `sandbox.validate_patch_source` (no imports, no dynamic
evaluation).
"""
from __future__ import annotations

import difflib
from typing import Any, Dict, List, Optional, Tuple

from src.layer2_diagnostician.agent import DiagnosticReport
from src.utils import config

NUMERIC_TYPES = {"float", "int"}

#: Key under which the generated parser records what it changed.
PROVENANCE_KEY = "_healing"

#: Key listing fields whose value was invented or altered under a
#: quarantine policy. Its presence means the record must be kept out of
#: the main stream.
QUARANTINE_KEY = "_quarantine"

#: Provenance actions that mean the emitted value did not arrive in the
#: payload. A coercion is excluded: '42.5' -> 42.5 preserves the value,
#: it does not invent one.
INVENTING_ACTIONS = (
    "defaulted",
    "defaulted_blank",
    "rejected_bool",
    "clamped_to_min",
    "clamped_to_max",
)

#: Bookkeeping keys that are never treated as payload data.
RESERVED_KEYS = (
    PROVENANCE_KEY, QUARANTINE_KEY, "_is_duplicate",
    "_is_duplicate_flag", "duplicate_uuid",
)

#: Escalation ladder. Attempt N uses STRATEGIES[N - 1].
STRATEGIES = ("strict", "fuzzy_alias", "defensive")

_TEMPLATE = '''# Auto-Generated Self-Healing Data Pipeline Parser
# Generated by the Layer 3 Patch Generator
#
# Pipeline        : {pipeline_id}
# Strategy        : {strategy} (attempt {attempt})
# Diagnosis       : {cause}
# Affected field  : {affected_field} ({anomaly_category})
{feedback_comment}
# Normalisation applied:
#   - alias recovery for renamed upstream keys
#   - type coercion against the declared schema
#   - safe defaults for missing or null fields
#   - clamping of numeric values to their declared valid range
#   - {extras_note}
#   - quarantine flagging for: {quarantine_note}
#
# Every field this parser touches is recorded under the PROVENANCE_KEY of the
# returned record, so a downstream consumer can tell a value that genuinely
# arrived from one this parser invented. Fields absent from that block passed
# through untouched.
#
# Fields under a quarantine policy are listed under QUARANTINE_KEY when their
# value was invented or altered. The record keeps a valid shape so it can
# still flow through typed systems, but its presence means the record must
# NOT be aggregated or treated as a genuine observation.

SCHEMA = {schema!r}
RANGES = {ranges!r}
DEFAULTS = {defaults!r}
ALIASES = {aliases!r}
RESERVED_KEYS = {reserved!r}
PRESERVE_UNKNOWN_FIELDS = {preserve_unknown!r}
AGGRESSIVE_NUMERIC_RECOVERY = {aggressive!r}
PROVENANCE_KEY = {provenance_key!r}
QUARANTINE_KEY = {quarantine_key!r}
QUARANTINE_FIELDS = {quarantine_fields!r}
INVENTING_ACTIONS = {inventing_actions!r}


def _note(provenance, field, action, original):
    """Record that `field` was altered, and what it held beforehand."""
    entry = provenance.get(field)
    if entry is None:
        entry = {{"actions": [], "original": original}}
        provenance[field] = entry
    entry["actions"].append(action)
    if entry["original"] is None and original is not None:
        entry["original"] = original
    return provenance


def _salvage_number(text, default):
    """Last-resort numeric recovery from a dirty string like \'~22.5 degC\'."""
    kept = ""
    for char in text:
        if char.isdigit() or char in "+-.eE":
            kept = kept + char
    try:
        return float(kept)
    except (ValueError, TypeError):
        return default


def _to_number(value, default):
    """Coerce a value to float, falling back to a schema-safe default."""
    if value is None or isinstance(value, bool):
        return default
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        stripped = value.strip()
        if not stripped:
            return default
        try:
            return float(stripped)
        except (ValueError, TypeError):
            if AGGRESSIVE_NUMERIC_RECOVERY:
                return _salvage_number(stripped, default)
            return default
    return default


def _to_text(value, default):
    """Coerce a value to str, falling back to a schema-safe default."""
    if value is None:
        return default
    if isinstance(value, str):
        return value if value.strip() else default
    return str(value)


def parse_payload(payload: dict) -> dict:
    """Normalise one ingestion record against the pipeline schema.

    Works on a copy: the caller\'s dict is never mutated.
    """
    source = dict(payload)
    parsed = {{}}
    provenance = {{}}

    # 1. Recover fields the upstream provider renamed.
    for alias, canonical in ALIASES.items():
        if canonical not in source and alias in source:
            source[canonical] = source.pop(alias)
            _note(provenance, canonical, "aliased_from:" + alias, None)

    # 2. Coerce, default and clamp every declared field.
    for field, declared in SCHEMA.items():
        default = DEFAULTS[field]
        value = source.get(field)
        missing = field not in source or value is None

        if declared == "str":
            if missing:
                _note(provenance, field, "defaulted", None)
            elif not isinstance(value, str):
                _note(provenance, field, "coerced_to_str", value)
            elif not value.strip():
                _note(provenance, field, "defaulted_blank", value)
            parsed[field] = _to_text(value, default)
            continue

        if missing:
            _note(provenance, field, "defaulted", None)
        elif isinstance(value, bool):
            _note(provenance, field, "rejected_bool", value)
        elif not isinstance(value, (int, float)):
            _note(provenance, field, "coerced_to_number", value)

        number = _to_number(value, default)
        bounds = RANGES.get(field)
        if bounds is not None:
            if number < bounds[0]:
                _note(provenance, field, "clamped_to_min", number)
                number = bounds[0]
            elif number > bounds[1]:
                _note(provenance, field, "clamped_to_max", number)
                number = bounds[1]
        parsed[field] = number

    # 3. Carry through fields the schema does not describe, so healing never
    #    silently drops data it simply did not recognise.
    if PRESERVE_UNKNOWN_FIELDS:
        for key, value in source.items():
            if key not in parsed and key not in RESERVED_KEYS:
                parsed[key] = value
    else:
        for key in source:
            if key not in SCHEMA and key not in RESERVED_KEYS:
                _note(provenance, key, "dropped_unrecognised", source[key])

    # 4. Attach provenance only when something was actually altered, so a
    #    clean record stays byte-identical to its input.
    if provenance:
        parsed[PROVENANCE_KEY] = provenance

    # 5. Flag the record when a field that cannot tolerate an invented
    #    value got one. Backfilling an identity or a monetary amount
    #    produces a row that passes validation and then corrupts every
    #    aggregate computed over it, so such a record is marked rather
    #    than quietly emitted as though it were genuine.
    quarantined = []
    for field in QUARANTINE_FIELDS:
        entry = provenance.get(field)
        if entry is None:
            continue
        for action in entry["actions"]:
            if action in INVENTING_ACTIONS and field not in quarantined:
                quarantined.append(field)

    if quarantined:
        parsed[QUARANTINE_KEY] = quarantined

    return parsed
'''


def default_for(field: str, declared: str, ranges: Dict[str, Tuple[float, float]]) -> Any:
    """Pick a backfill default that satisfies the field's own constraints.

    A flat 0.0 (the previous behaviour) is invalid for a field like finance
    `amount`, whose declared range starts at 0.01 -- the patch would heal the
    record into a value the verifier then rejects.
    """
    if declared in NUMERIC_TYPES:
        bounds = ranges.get(field)
        if bounds:
            low, high = float(bounds[0]), float(bounds[1])
            return min(max(0.0, low), high)
        return 0.0

    lowered = field.lower()
    if "time" in lowered or "date" in lowered:
        return "1970-01-01T00:00:00"
    return ""


class PatchGenerator:
    """Synthesises a `parse_payload` function for a diagnosed failure."""

    def __init__(self, similarity_threshold: Optional[float] = None):
        self.similarity_threshold = (
            similarity_threshold
            if similarity_threshold is not None
            else config.KEY_SIMILARITY_THRESHOLD
        )

    def generate_patch(
        self,
        diagnostic: DiagnosticReport,
        schema_spec: Optional[Dict[str, str]] = None,
        valid_ranges: Optional[Dict[str, Tuple[float, float]]] = None,
        observed_payload: Optional[Dict[str, Any]] = None,
        feedback_context: str = "",
        attempt: int = 1,
        pipeline_id: str = "weather",
        known_aliases: Optional[Dict[str, str]] = None,
        quarantine_fields: Optional[Tuple[str, ...]] = None,
    ) -> str:
        """Return executable patch source for this diagnosis.

        `attempt` selects the escalation strategy, so successive retries
        after a failed verification produce materially different code.
        """
        if schema_spec is None:
            from src.ingestion.pipeline_registry import registry
            pipeline = registry.require_pipeline(pipeline_id)
            schema_spec = pipeline.get_schema_spec()
            valid_ranges = valid_ranges or pipeline.valid_ranges
            if known_aliases is None:
                known_aliases = {
                    alias: canonical
                    for canonical, alias in pipeline.field_renames.items()
                }
            if quarantine_fields is None:
                quarantine_fields = pipeline.quarantine_fields()

        schema = {
            field: (declared if isinstance(declared, str) else getattr(declared, "__name__", "str"))
            for field, declared in schema_spec.items()
        }
        ranges = {
            field: (float(bounds[0]), float(bounds[1]))
            for field, bounds in (valid_ranges or {}).items()
            if field in schema
        }
        defaults = {field: default_for(field, declared, ranges) for field, declared in schema.items()}

        strategy = STRATEGIES[min(max(attempt, 1), len(STRATEGIES)) - 1]
        aliases = self._build_aliases(
            diagnostic, schema, observed_payload, strategy, known_aliases or {}
        )

        preserve_unknown = strategy != "defensive"
        aggressive = strategy == "defensive"
        extras_note = (
            "unrecognised fields preserved"
            if preserve_unknown
            else "unrecognised fields dropped (defensive strategy)"
        )
        applicable_quarantine = tuple(
            field for field in (quarantine_fields or ()) if field in schema
        )
        quarantine_note = (
            ", ".join(applicable_quarantine) if applicable_quarantine else "(none)"
        )

        feedback_comment = "#"
        if feedback_context:
            collapsed = " ".join(feedback_context.split())[:300]
            feedback_comment = f"# Prior attempt feedback: {collapsed}"

        return _TEMPLATE.format(
            pipeline_id=pipeline_id,
            strategy=strategy,
            attempt=attempt,
            cause=" ".join(str(diagnostic.cause).split())[:200],
            affected_field=diagnostic.affected_field,
            anomaly_category=diagnostic.anomaly_category,
            feedback_comment=feedback_comment,
            extras_note=extras_note,
            quarantine_note=quarantine_note,
            schema=schema,
            ranges=ranges,
            defaults=defaults,
            aliases=aliases,
            reserved=RESERVED_KEYS,
            provenance_key=PROVENANCE_KEY,
            quarantine_key=QUARANTINE_KEY,
            quarantine_fields=tuple(
                field for field in (quarantine_fields or ()) if field in schema
            ),
            inventing_actions=INVENTING_ACTIONS,
            preserve_unknown=preserve_unknown,
            aggressive=aggressive,
        )

    # -- alias discovery -----------------------------------------------------

    def _build_aliases(
        self,
        diagnostic: DiagnosticReport,
        schema: Dict[str, str],
        observed_payload: Optional[Dict[str, Any]],
        strategy: str,
        known_aliases: Dict[str, str],
    ) -> Dict[str, str]:
        """Map observed key -> canonical schema field.

        Three sources, in descending order of trust:
          1. the pipeline's declared rename table -- authoritative config,
             and the only thing that catches a semantic rename such as
             reorder_level -> min_stock, which scores 0.09 on string
             similarity and is invisible to lexical matching;
          2. the Layer 2 diagnosis for this specific failure;
          3. lexical fuzzy matching, on the escalated strategies only,
             which recovers multi-field drift and cases where Layer 2
             named the wrong field.
        """
        aliases: Dict[str, str] = {
            alias: canonical
            for alias, canonical in known_aliases.items()
            if canonical in schema
        }

        replacement = diagnostic.found_replacement_key
        if replacement and diagnostic.affected_field in schema:
            aliases[replacement] = diagnostic.affected_field

        if strategy == "strict" or not observed_payload:
            return aliases

        observed = set(observed_payload.keys())
        missing = [field for field in schema if field not in observed]
        unclaimed = [
            key for key in observed
            if key not in schema and key not in aliases and key not in RESERVED_KEYS
        ]

        for field in missing:
            if field in aliases.values():
                continue
            best_key, best_score = None, 0.0
            for key in unclaimed:
                score = difflib.SequenceMatcher(None, key, field).ratio()
                if score > best_score:
                    best_key, best_score = key, score
            if best_key and best_score >= self.similarity_threshold:
                aliases[best_key] = field
                unclaimed.remove(best_key)

        return aliases

    @staticmethod
    def describe_strategy(attempt: int) -> str:
        """Name the strategy a given attempt will use (for logging)."""
        return STRATEGIES[min(max(attempt, 1), len(STRATEGIES)) - 1]

    @staticmethod
    def available_strategies() -> List[str]:
        return list(STRATEGIES)
